export function t(key: string): string {
    // Check exact match first
    if (japaneseDict[key]) return japaneseDict[key];

    // Handle regional forms dynamically (e.g., "Rattata-Alola" -> "ラッタ(アローラ)")
    const regionalSuffixes: { [key: string]: string } = {
        '-Alola': '(アローラ)',
        '-Galar': '(ガラル)',
        '-Hisui': '(ヒスイ)',
        '-Paldea': '(パルデア)'
    };

    for (const [suffix, translation] of Object.entries(regionalSuffixes)) {
        if (key.endsWith(suffix)) {
            const baseName = key.slice(0, -suffix.length);
            const baseTranslation = japaneseDict[baseName] || baseName;
            return baseTranslation + translation;
        }
    }

    return key;
}

// Type-specific translation (handles "Psychic" → "エスパー" conflict with move "Psychic" → "サイコキネシス")
const TYPE_OVERRIDES: Record<string, string> = { "Psychic": "エスパー" };
export function tType(key: string): string {
    return TYPE_OVERRIDES[key] || t(key);
}

export function toEnglish(key: string): string {
    // Check exact match first
    if (reverseJapaneseDict[key]) return reverseJapaneseDict[key];

    // Handle regional forms dynamically (e.g., "ラッタ(アローラ)" or "ラッタ（アローラ）" -> "Rattata-Alola")
    // Support both half-width () and full-width （）parentheses
    const regionalPatterns = [
        { pattern: /[\(（]アローラ[\)）]$/, suffix: '-Alola' },
        { pattern: /[\(（]ガラル[\)）]$/, suffix: '-Galar' },
        { pattern: /[\(（]ヒスイ[\)）]$/, suffix: '-Hisui' },
        { pattern: /[\(（]パルデア[\)）]$/, suffix: '-Paldea' }
    ];

    for (const { pattern, suffix } of regionalPatterns) {
        if (pattern.test(key)) {
            const baseName = key.replace(pattern, '');
            const baseEnglish = reverseJapaneseDict[baseName] || baseName;
            return baseEnglish + suffix;
        }
    }

    return key;
}

export function translateText(text: string): string {
    let translated = text;
    // Replace known terms
    // Sort keys by length descending to match longest phrases first (simple heuristic)
    // Update: This is expensive if dict grows to 2000+. 
    // Optimization: Only scan for keys present in text? Or simple exact match first?
    // For specific UI labels, t() is preferred. translateText() is for sentences.

    // If exact match
    if (japaneseDict[text]) return japaneseDict[text];

    const sortedKeys = Object.keys(japaneseDict).sort((a, b) => b.length - a.length);

    for (const key of sortedKeys) {
        // Regex to replace whole words or specific phrases if possible
        // For now simple string replace
        // Escaping regex characters in key might be needed if they contain specials
        if (translated.includes(key)) {
            translated = translated.split(key).join(japaneseDict[key]);
        }
    }

    // Custom replacements for english structural words from smogon desc
    translated = translated
        .replace(" vs. ", " vs ")
        .replace(" SpA ", " 特攻 ")
        .replace(" Atk ", " 攻撃 ")
        .replace(" Def ", " 防御 ")
        .replace(" SpD ", " 特防 ")
        .replace(" HP ", " HP ")
        .replace(" -- ", " -- ")
        // Result phrases
        .replace(/guaranteed (\d+)HKO/g, "確定$1発")
        .replace(/(\d+(\.\d+)?)% chance to OHKO/g, "乱数1発 ($1%)")
        .replace(/(\d+(\.\d+)?)% chance to (\d+)HKO/g, "乱数$3発 ($1%)")
        .replace(/possible (\d+)HKO/g, "乱数$1発") // Fallback for no percentage (smogon default)
        .replace(/possible OHKO/g, "乱数1発")
        .replace(/chance to (\d+)HKO/g, "乱数$1発") // Fallback for chance to without percentage
        .replace(/(\d+) hits/g, "$1回ヒット") // "hits or more"?
        .replace(/(\d+) hits? or more/g, "$1回以上ヒット") // Handle "4 hits or more"
        .replace(/approx\. /g, "")
        // Catch-all for bare OHKO/XHKO (e.g. after approx. removal)
        .replace(/(?<![確乱])(\d+)HKO/g, "確定$1発")
        .replace(/(?<![確乱])OHKO/g, "確定1発");

    return translated;
}

